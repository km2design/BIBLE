export function getMatthewEpisode(id: string): Episode | undefined {
  return matthewEpisodes.find((e) => e.id === id)
}

export function nextMatthewEpisode(id: string): Episode | undefined {
  const i = matthewEpisodes.findIndex((e) => e.id === id)
  if (i < 0 || i >= matthewEpisodes.length - 1) return undefined
  return matthewEpisodes[i + 1]
}
